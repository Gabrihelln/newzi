export function topicIconFor(topic: { code?: string; name?: string }): TopicIconName {
  const name = normalize(topic.name || ''), code = (topic.code || '').toLowerCase();
  return RULES.find(([pattern]) => pattern.test(name) || pattern.test(code))?.[1] || 'news';
}

